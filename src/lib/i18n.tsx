export function translate(language: Language, text: string, values: Record<string, string | number> = {}) {
  const template = language === "ar" ? ARABIC[text] ?? text : text;
  return template.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match));
}
export function readLanguage(): Language {
  try { return localStorage.getItem(LANGUAGE_KEY) === "ar" ? "ar" : "en"; } catch { return "en"; }
}
const LanguageContext = createContext({ language: "en" as Language, setLanguage: (_language: Language) => {}, t: (text: string, values?: Record<string, string | number>) => translate("en", text, values) });
export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setCurrent] = useState<Language>("en");
  useEffect(() => { setCurrent(readLanguage()); }, []);
  useEffect(() => { document.documentElement.lang = language; document.documentElement.dir = language === "ar" ? "rtl" : "ltr"; }, [language]);
  const setLanguage = (next: Language) => { setCurrent(next); try { localStorage.setItem(LANGUAGE_KEY, next); } catch { /* in-memory preference still works */ } };
  return <LanguageContext.Provider value={{ language, setLanguage, t: (text, values) => translate(language, text, values) }}>{children}</LanguageContext.Provider>;
}
export const useLanguage = () => useContext(LanguageContext);
